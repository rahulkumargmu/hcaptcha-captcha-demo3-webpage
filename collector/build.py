"""Build the regular-browser collectors from the single collector core.

  build_site_collector(out_file, cfg)  -> website script (core + addons/site.js)
  build_extension(out_dir, cfg)        -> unpacked Chrome extension (core + addons/frame_observer.js,
                                          bridge, service worker, manifest)

Both embed the configuration and the SHA-256 of every source they were built from, so an
export can be traced back to the exact collector version.
"""

from __future__ import annotations

import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit

from .build_config import COLLECTOR_VERSION, NOT_MONITORED, PROJECT_DIR, SCHEMA_VERSION

PKG = Path(__file__).resolve().parent
CORE = PKG / "collector.js"
SITE_ADDON = PKG / "addons" / "site.js"
FRAME_ADDON = PKG / "addons" / "frame_observer.js"
SYNTH_MODULE = PKG / "synthetic_ctx.js"
EXT_SRC = PKG / "extension_src"
CAPTURE_SRC = PROJECT_DIR / "collector-capture.js"
CONFIG_MARKER = "/*__VMC_CONFIG__*/ null"
ADDON_MARKER = "/*__VMC_ADDONS__*/"


def experiment_origins(cfg: dict) -> list[str]:
    """Keep all injection and runtime checks on the same exact-origin allowlist."""
    origins = cfg.get("experiment_origins", [cfg["experiment_origin"]])
    if not isinstance(origins, list) or not origins:
        raise ValueError("experiment_origins must be a non-empty list of exact origins")
    result = list(dict.fromkeys([cfg["experiment_origin"], *origins]))
    for origin in result:
        parts = urlsplit(origin)
        if (parts.scheme not in {"http", "https"} or not parts.hostname
                or parts.username or parts.password or parts.path or parts.query or parts.fragment
                or "*" in origin):
            raise ValueError(f"Not an exact HTTP(S) experiment origin: {origin!r}")
    return result


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _sources(paths: list[Path]) -> list[dict]:
    return [{"path": str(p.relative_to(PROJECT_DIR)), "sha256": _sha(p)} for p in paths]


def _bundle(addon: Path, cfg: dict) -> str:
    core = CORE.read_text()
    if core.count(CONFIG_MARKER) != 1 or core.count(ADDON_MARKER) != 1:
        raise SystemExit("collector.js must contain each placeholder exactly once")
    return core.replace(ADDON_MARKER, addon.read_text(), 1).replace(CONFIG_MARKER, json.dumps(cfg, separators=(",", ":")), 1)


def _header(kind: str, sources: list[dict]) -> str:
    lines = [f"// GENERATED by vm_data_generation/collector/build.py — {kind}.",
             f"// collector {COLLECTOR_VERSION}, schema {SCHEMA_VERSION}, built {datetime.now(timezone.utc).isoformat()}.",
             "// Do not edit; rebuild from the collector sources:"]
    lines += [f"//   {s['path']} sha256={s['sha256']}" for s in sources]
    return "\n".join(lines) + "\n"


def site_config(cfg: dict) -> dict:
    srcs = _sources([CORE, SITE_ADDON, SYNTH_MODULE])
    return {
        "schema_version": SCHEMA_VERSION,
        "collector_version": COLLECTOR_VERSION,
        "collection_context": "site_collector",
        "experiment_origin": cfg["experiment_origin"],
        "experiment_origins": experiment_origins(cfg),
        "config_sha256": cfg.get("config_sha256"),
        "collector": cfg["collector"],
        "vm_observer": {"enabled": False},
        "control_panel": "none",
        "widget_container_selector": cfg.get("site", {}).get("widget_container_selector", "#hcaptcha-widget"),
        "site": {"experiment_name": cfg.get("experiment_name"), "experiment_url": cfg["experiment_url"],
                 "comparison": cfg.get("comparison", {}),
                 # Emit the labelled synthetic six-field hsw_ctx fixture in the export (offline parser
                 # test artifact; never submitted). Disable with experiment.json site.synthetic_ctx_fixture=false.
                 "synthetic_ctx_fixture": cfg.get("site", {}).get("synthetic_ctx_fixture", True)},
        "not_monitored": NOT_MONITORED,
        "build": {"built_utc": datetime.now(timezone.utc).isoformat(), "builder": "collector/build.py", "sources": srcs},
    }


def build_site_collector(out_file: Path, cfg: dict) -> Path:
    out_file = Path(out_file)
    sc = site_config(cfg)
    # The synthetic-fixture module attaches self.VMC_SYNTHETIC_CTX at top level, before the core IIFE
    # runs, so addons/site.js can read it during export. It is pure (no page or network access).
    js = (_header("website collector (parent page)", sc["build"]["sources"])
          + SYNTH_MODULE.read_text() + "\n" + _bundle(SITE_ADDON, sc))
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(js)
    return out_file


def extension_config(cfg: dict) -> dict:
    vm = dict(cfg["vm_observer"])
    return {"experiment_origin": cfg["experiment_origin"], "experiment_origins": experiment_origins(cfg),
            "experiment_url": cfg["experiment_url"],
            "frame_url_prefixes": vm.get("frame_url_prefixes", [])}


def source_capture_config(cfg: dict) -> dict:
    """The scope the armed debugger transport enforces. Derived from the conservative default for the
    experiment origin, with any explicit overrides from cfg['source_capture']. The application script
    is included only when named, so a blanket origin capture is never implied."""
    from .srcarchive import default_scope

    origin = cfg["experiment_origin"]
    sc = cfg.get("source_capture") or {}
    scope = default_scope(origin, include_application_script=sc.get("include_application_script"))
    for key in ("allow", "allow_methods", "deny_path_substrings", "max_body_bytes", "max_total_bytes",
                "max_concurrent_body_reads", "body_read_timeout_ms", "export_timeout_ms"):
        if key in sc:
            scope[key] = sc[key]
    return {"experiment_origin": origin, "transport": "chrome_debugger_cdp", "scope": scope}


def build_extension(out_dir: Path, cfg: dict, *, source_capture: bool = False) -> Path:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    extra = [EXT_SRC / "source_scope.js", EXT_SRC / "source_capture.js", EXT_SRC / "popup.js",
             EXT_SRC / "popup.html"] if source_capture else []
    srcs = _sources([PKG / "build.py", PKG / "build_config.py", CORE, FRAME_ADDON,
                     EXT_SRC / "bridge.js", EXT_SRC / "background.js",
                     EXT_SRC / "hsw_capture_download.js", CAPTURE_SRC,
                     EXT_SRC / "manifest.template.json", *extra])
    obs_cfg = {
        "schema_version": SCHEMA_VERSION,
        "collector_version": COLLECTOR_VERSION,
        "collection_context": "extension_frame_observer",
        "experiment_origin": cfg["experiment_origin"],
        "experiment_origins": experiment_origins(cfg),
        "config_sha256": cfg.get("config_sha256"),
        "collector": cfg["collector"],
        "vm_observer": {**cfg["vm_observer"], "enabled": True},
        "control_panel": "none",
        "build": {"built_utc": datetime.now(timezone.utc).isoformat(), "builder": "collector/build.py", "sources": srcs},
    }
    (out_dir / "observer-main.js").write_text(_header("frame observer (MAIN world)", srcs) + _bundle(FRAME_ADDON, obs_cfg))
    ext_cfg = extension_config(cfg)
    if source_capture:
        ext_cfg["source_capture"] = source_capture_config(cfg)
    (out_dir / "config.js").write_text("// GENERATED by collector/build.py\nself.VMC_EXTENSION_CONFIG = "
                                       + json.dumps({**ext_cfg, "build": obs_cfg["build"]}, indent=2) + ";\n")
    shutil.copyfile(EXT_SRC / "bridge.js", out_dir / "bridge.js")
    shutil.copyfile(EXT_SRC / "background.js", out_dir / "background.js")
    shutil.copyfile(EXT_SRC / "hsw_capture_download.js", out_dir / "hsw_capture_download.js")
    (out_dir / "collector-capture.js").write_text(
        "globalThis.__VMC_HSW_CAPTURE_ORIGINS = " + json.dumps(experiment_origins(cfg)) + ";\n"
        + CAPTURE_SRC.read_text())
    for p in extra:
        shutil.copyfile(p, out_dir / p.name)
    origins = experiment_origins(cfg)
    prefixes = ext_cfg["frame_url_prefixes"]
    hosts = sorted({f"{urlsplit(p).scheme}://{urlsplit(p).netloc}/*" for p in prefixes}
                   | {origin + "/*" for origin in origins})
    observer_matches = [p.rstrip("*") + "*" if p.endswith("/") else p + "*" for p in prefixes]
    manifest = (EXT_SRC / "manifest.template.json").read_text()
    manifest = manifest.replace("__VERSION__", COLLECTOR_VERSION).replace("__HOST_PERMISSIONS__", json.dumps(hosts)) \
        .replace("__BRIDGE_MATCHES__", json.dumps([origin + "/*" for origin in origins] + observer_matches)) \
        .replace("__OBSERVER_MATCHES__", json.dumps(observer_matches))
    man = json.loads(manifest)  # must be valid JSON
    man["name"] = cfg.get("extension", {}).get("name", man["name"])
    man["version"] = cfg.get("extension", {}).get("version", man["version"])
    if not source_capture:
        (out_dir / "manifest.json").write_text(json.dumps(man, indent=2) + "\n")
        return out_dir
    # The new privilege: chrome.debugger for CDP network observation on the one armed tab, plus a
    # trusted popup to arm it. The base observer's permissions and content-script matches are
    # otherwise unchanged. Documented for the user before activation (docs/SOURCE_ARCHIVE.md).
    man["name"] = man["name"] + " + source archiver"
    man["description"] = (man["description"] + " Opt-in: can attach chrome.debugger to the one armed experiment "
                          "tab to archive allowlisted public static resource bodies.")
    man["permissions"] = sorted(set(man.get("permissions", [])) | {"debugger", "tabs"})
    man["action"] = {"default_popup": "popup.html", "default_title": "VMC source capture"}
    (out_dir / "manifest.json").write_text(json.dumps(man, indent=2) + "\n")
    return out_dir
